"""Write the package construct.py: literal hunks base -> candidate (difflib on JSON events)."""
import sys, json, gzip, difflib
rd = lambda p: json.loads(gzip.decompress(open(p, 'rb').read()))
base, cand, out = rd(sys.argv[1]), rd(sys.argv[2]), sys.argv[3]
for k in base:
    if k not in ('program', 'initial', 'final', 'frames'): assert base[k] == cand[k], k
assert cand['frames'][:len(base['frames'])] == base['frames']
newframes = cand['frames'][len(base['frames']):]
A = [json.dumps(e) for e in base['program']]; B = [json.dumps(e) for e in cand['program']]
sm = difflib.SequenceMatcher(None, A, B, autojunk=False)
hunks = [(i1, i2, base['program'][i1:i2], cand['program'][j1:j2]) for t, i1, i2, j1, j2 in sm.get_opcodes() if t != 'equal']
ini = {r: (a, b) for r, (a, b) in enumerate(zip(base['initial'], cand['initial'])) if a != b}
fin = {r: (a, b) for r, (a, b) in enumerate(zip(base['final'], cand['final'])) if a != b}
L = []
L.append('"""Literal edits from the PR5580 P104 word to the R22 reorder+reframe optimum.\n\nGenerated by tools/gen_construct.py from the solver output; replay needs no solver.\nJoel Pulikkan (GamingPuzzled) with Claude Opus 5.5 (Anthropic) via Claude Code. Apache-2.0.\nThe source word is by aliromman, GamingPuzzled, DreamingOfClouds, thu-nmrc and the retained P104 contributors.\n"""')
L.append('from copy import deepcopy\n\n\ndef need(ok, why):\n    if not ok:\n        raise ValueError(why)\n')
L.append('# (base start, base stop, exact base events, replacement events); base = PR5580 WORD.json.gz program')
L.append('EDITS = [')
for h in hunks: L.append('    (%d, %d,\n     %s,\n     %s),' % (h[0], h[1], repr(h[2]), repr(h[3])))
L.append(']')
L.append('INITIAL = %s  # helper: (base initial frame, new initial frame)' % json.dumps({str(k): v for k, v in ini.items()}))
L.append('FINAL = %s' % json.dumps({str(k): v for k, v in fin.items()}))
L.append('NEW_FRAMES = %s\n' % repr(newframes))
L.append('''
def construct(source):
    word = deepcopy(source)
    old = source['program']
    need(len(old) == %d, 'Exact source event count')
    new, k = [], 0
    for start, stop, before, after in EDITS:
        need(k <= start and old[start:stop] == before, 'Exact source events at %%d' %% start)
        new += deepcopy(old[k:start]) + deepcopy(after)
        k = stop
    new += deepcopy(old[k:])
    word['program'] = new
    word['frames'] = deepcopy(source['frames']) + deepcopy(NEW_FRAMES)
    for key, table in (('initial', INITIAL), ('final', FINAL)):
        for r, (a, b) in table.items():
            need(word[key][int(r)] == a, 'Exact source endpoint')
            word[key][int(r)] = b
    return word
''' % len(base['program']))
open(out, 'w').write('\n'.join(L))
print('hunks', len(hunks), 'initial', ini, 'final', fin, 'new frames', len(newframes))
